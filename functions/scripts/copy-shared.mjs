/**
 * Copies the course editor's content types, validator, built-in tracks and language rules from the web app into functions/src/shared/, so the editor
 * and publishUnit run the exact same checks. Runs before every build (npm "prebuild"). The copies are committed:
 * where the web app isn't present (Cloud Build), this does nothing and the committed copies are used.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const from = join(here, "../../apps/web/src/content");
const to = join(here, "../src/shared");
export const FILES = ["types.ts", "validate.ts", "tracks.ts", "languages.ts", "robot.ts", "runtimes.ts"];
export const HEADER = "// GENERATED by functions/scripts/copy-shared.mjs from apps/web/src/content/ — edit the web copy, not this one.\n";
/** NodeNext needs explicit extensions on relative imports. */
export const transform = (src) => HEADER + src.replace(/from "\.\/([\w-]+)";/g, 'from "./$1.js";');

/** The Labs apps' ids (each folder's meta.ts), so `collect` counts only real labs (TECHNICAL.md "Security"). */
export function labIds(dir = join(here, "../../apps/web/src/labs/apps")) {
  return readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(join(dir, d.name, "meta.ts")))
    .map((d) => /\bid:\s*"([a-z][a-z0-9-]{1,39})"/.exec(readFileSync(join(dir, d.name, "meta.ts"), "utf8"))?.[1]).filter(Boolean).sort();
}
export const labsFile = (ids = labIds()) => `// GENERATED by functions/scripts/copy-shared.mjs from apps/web/src/labs/apps/*/meta.ts — add a lab there, not here.
export const LAB_IDS: readonly string[] = ${JSON.stringify(ids)};
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(from)) { console.log("copy-shared: apps/web not found, keeping the committed copies"); process.exit(0); }
  mkdirSync(to, { recursive: true });
  for (const f of FILES) writeFileSync(join(to, f), transform(readFileSync(join(from, f), "utf8")));
  writeFileSync(join(to, "labs.ts"), labsFile());
  console.log(`copy-shared: ${FILES.join(", ")}, labs.ts → src/shared/`);
}
